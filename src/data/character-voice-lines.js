export function getCharacterVoicePath(role, mood, index) {
  const character = CHARACTER_VOICE_PHRASES[role];
  return `/audio/voices/${character.folder}/${mood}/${String(index + 1).padStart(2, '0')}.mp3`;
}

export const CHARACTER_VOICE_LINES = Object.freeze(
  Object.fromEntries(Object.entries(CHARACTER_VOICE_PHRASES).map(([role, character]) => [
    role,
    {
      happy: character.happy.map((_, index) => getCharacterVoicePath(role, 'happy', index)),
      unhappy: character.unhappy.map((_, index) => getCharacterVoicePath(role, 'unhappy', index)),
    },
  ])),
);

