const itemTitleIndexes = new Map();
const categoryOffsets = new Map();

items.forEach((item) => {
  const itemIndex = categoryOffsets.get(item.categoryId) ?? 0;
  categoryOffsets.set(item.categoryId, itemIndex + 1);
  const englishTitle = ITEM_TITLES_EN[item.categoryId]?.[itemIndex];
  if (englishTitle) itemTitleIndexes.set(`${item.categoryId}:${item.id}`, englishTitle);
});

export function getLocalizedItemTitle(item, locale = 'ru') {
  if (!item) return '';
  if (locale !== 'en') return item.title;
  return itemTitleIndexes.get(`${item.categoryId}:${item.id}`) ?? item.title;
}

export function getLocalizedCategoryTitle(category, locale = 'ru') {
  if (!category) return '';
  if (locale !== 'en') return category.title;
  return CATEGORY_TITLES_EN[category.id] ?? category.title;
}
